import puppeteer from 'puppeteer-core'
import fs from 'node:fs'
import path from 'node:path'

const ROOT = 'D:/spss/app/dist'
const types = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8', '.woff': 'font/woff', '.woff2': 'font/woff2',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.json': 'application/json',
  '.sav': 'application/x-spss-sav',
}

console.log('--- Starting Puppeteer E2E Verification for AI Agent Co-Pilot & MCP ---')

const browser = await puppeteer.launch({
  executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe',
  headless: 'new',
  userDataDir: 'D:/spss/app/.chrome-verify-ai',
  args: ['--no-sandbox', '--disable-gpu', '--force-device-scale-factor=1', '--disable-dev-shm-usage'],
  defaultViewport: { width: 1440, height: 900, deviceScaleFactor: 1 },
})

const page = await browser.newPage()
await page.setRequestInterception(true)
page.on('request', (req) => {
  const url = new URL(req.url())
  if (url.hostname !== 'spss.local') return req.abort()
  let p = decodeURIComponent(url.pathname)
  if (p === '/' || p === '') p = '/index.html'
  const file = path.join(ROOT, p)
  if (fs.existsSync(file) && fs.statSync(file).isFile()) {
    req.respond({ status: 200, contentType: types[path.extname(file)] ?? 'application/octet-stream', body: fs.readFileSync(file) })
  } else {
    req.respond({ status: 404, body: 'Not found: ' + p })
  }
})

const errors = []
page.on('console', (msg) => {
  if (msg.type() === 'error') {
    errors.push(msg.text())
    console.error('[BROWSER ERROR]', msg.text())
  }
})

await page.goto('http://spss.local/#/workspace', { waitUntil: 'networkidle0' })
await new Promise((r) => setTimeout(r, 1200))

// 1. Verify window.__SPSS_AGENT_API__
const apiCheck = await page.evaluate(() => {
  const api = window.__SPSS_AGENT_API__
  return {
    hasApi: typeof api !== 'undefined',
    version: api?.version,
    rowCount: api?.getDataset()?.rows?.length,
    varsCount: api?.getVariables()?.length,
  }
})
console.log('API Check:', apiCheck)
if (!apiCheck.hasApi || apiCheck.rowCount < 100 || apiCheck.varsCount < 7) {
  throw new Error('window.__SPSS_AGENT_API__ is not properly initialized on the page!')
}
console.log('✓ window.__SPSS_AGENT_API__ active and verified!')

// 2. Click the AI Agent button on the toolbar
console.log('Clicking button.tool-ai-btn...')
await page.click('button.tool-ai-btn')
await new Promise((r) => setTimeout(r, 500))

const panelVisible = await page.evaluate(() => {
  const el = document.querySelector('.spss-ai-agent-panel')
  return el !== null && el.offsetWidth > 0
})
console.log('Panel visible after click:', panelVisible)
if (!panelVisible) throw new Error('AIAgentPanel did not open!')
console.log('✓ AIAgentPanel opened successfully via toolbar!')

// 3. Click "⚡ Analisis Skripsi Lengkap" quick action chip
console.log('Clicking "⚡ Analisis Skripsi Lengkap" chip...')
await page.click('button.chip-primary')
await new Promise((r) => setTimeout(r, 1200))

const outputNodes = await page.evaluate(() => {
  return window.__SPSS_AGENT_API__.getOutputs().map(o => o.title)
})
console.log('Output documents generated by AI Agent:', outputNodes)
if (outputNodes.length < 3) throw new Error('Failed to run full thesis analysis suite!')
console.log('✓ Full thesis analysis generated ' + outputNodes.length + ' output blocks!')

// 4. Test programmatic executeInstruction
console.log('Calling window.__SPSS_AGENT_API__.executeInstruction("Uji validitas dan reliabilitas instrumen")...')
const execRes = await page.evaluate(() => {
  return window.__SPSS_AGENT_API__.executeInstruction('Uji validitas dan reliabilitas instrumen')
})
console.log('executeInstruction result:', execRes)
if (!execRes.success) throw new Error('executeInstruction failed!')
console.log('✓ Programmatic executeInstruction verified!')

// 5. Test Compute Variable via agent API
console.log('Calling window.__SPSS_AGENT_API__.computeVariable("TOTAL_X", "Total Skor X", "X1_Harga + X2_Kualitas + X3_Promosi")...')
await page.evaluate(() => {
  window.__SPSS_AGENT_API__.computeVariable('TOTAL_X', 'Total Skor X', 'X1_Harga + X2_Kualitas + X3_Promosi')
})
await new Promise((r) => setTimeout(r, 400))
const hasNewVar = await page.evaluate(() => {
  return window.__SPSS_AGENT_API__.getVariables().some(v => v.name === 'TOTAL_X')
})
console.log('Computed variable TOTAL_X added to dataset:', hasNewVar)
if (!hasNewVar) throw new Error('computeVariable failed to add TOTAL_X!')
console.log('✓ Compute variable via API verified!')

console.log('Console errors encountered:', errors.length)
if (errors.length > 0) throw new Error('Browser console had errors: ' + errors.join('; '))

await browser.close()
console.log('\n🌟 ALL AI AGENT & MCP TESTS PASSED 100% CLEAN! 🌟')
